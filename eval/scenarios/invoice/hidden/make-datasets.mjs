// 乱数で作る大きめのデータ（シード固定）
const rand = (seed => () => ((seed = (seed * 1103515245 + 12345) % 2147483648) / 2147483648))(20261010)
const pick = xs => xs[Math.floor(rand() * xs.length)]
const closing = [5, 10, 15, 20, 25, 28, '末', '末']
const customers = Array.from({ length: 40 }, (_, i) => [
  `R${String(i + 1).padStart(3, '0')}`, `乱数顧客${i + 1}`, pick(closing), pick(['A', 'B', 'C']), pick(['一般', '一般', '特約店']),
  pick(['切り捨て', '四捨五入', '切り上げ', '']),
])
const products = []
for (let i = 1; i <= 30; i++) {
  const id = `Q${String(i).padStart(3, '0')}`
  const rate = rand() < 0.25 ? 8 : 10
  products.push([id, `乱数商品${i}`, 1 + Math.floor(rand() * 12000), rate, '2026-01-01'])
  if (rand() < 0.4) {
    const day = 1 + Math.floor(rand() * 60)
    products.push([id, `乱数商品${i}`, 1 + Math.floor(rand() * 12000), rand() < 0.1 ? 18 - rate : rate, new Date(Date.UTC(2026, 7, day)).toISOString().slice(0, 10)])
  }
}
const orders = []
for (let n = 1; n <= 300; n++) {
  const day = 1 + Math.floor(rand() * 92) // 2026-08-01 から 92 日
  const date = new Date(Date.UTC(2026, 7, day)).toISOString().slice(0, 10)
  const c = pick(customers)[0]
  const status = rand() < 0.08 ? '取消' : '確定'
  const used = new Set()
  const lines = 1 + Math.floor(rand() * 4)
  for (let l = 0; l < lines; l++) {
    const p = pick(products)[0]
    if (used.has(p)) continue // 同じ注文に同じ商品は1行まで
    used.add(p)
    orders.push([`N${String(n).padStart(4, '0')}`, date, c, p, rand() < 0.15 ? 100 + Math.floor(rand() * 200) : 1 + Math.floor(rand() * 60), status])
  }
}
const returns = []
let rn = 0
for (const o of orders) {
  if (o[5] !== '確定' || rand() > 0.12) continue
  const q = 1 + Math.floor(rand() * o[4])
  const d = new Date(Date.parse(o[1]) + (1 + Math.floor(rand() * 20)) * 86400000).toISOString().slice(0, 10)
  returns.push([`RR${String(++rn).padStart(3, '0')}`, d, o[0], o[3], q])
}
const payments = customers.filter(() => rand() < 0.6).map((c, i) => [`PP${i + 1}`, new Date(Date.UTC(2026, 7, 10 + Math.floor(rand() * 45))).toISOString().slice(0, 10), c[0], Math.floor(rand() * 50000)])
const balances = customers.filter(() => rand() < 0.6).map(c => [c[0], '2026-08', Math.floor(rand() * 60000)])
DATASETS.random = { month: '2026-09', customers, products, orders, returns, payments, balances }

rmSync(out, { recursive: true, force: true })
